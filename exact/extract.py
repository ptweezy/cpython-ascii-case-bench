"""Copy the PR's word helpers and _Py_bytes_lower/_Py_bytes_upper verbatim
from a CPython Objects/bytes_methods.c into pr_helpers.h, for check_exact.c.

    python extract.py PATH/TO/bytes_methods.c pr_helpers.h

Two edits only: the functions are renamed pr_bytes_lower/pr_bytes_upper,
and the MSVC test becomes CHECK_COUNT_WORDS so that both loops can be
compiled and checked with any compiler.
"""
import sys

src, out = sys.argv[1:3]
text = open(src, encoding="utf-8").read()
start = text.index("/* Return 0x20 in each byte")
upper = text.index("\n_Py_bytes_upper(", start)
end = text.index("\n}\n", upper) + 3
code = text[start:end]
msvc = "#if defined(_MSC_VER) && !defined(__clang__)"
assert code.count(msvc) == 1, "MSVC test not found"
code = code.replace(msvc, "#if CHECK_COUNT_WORDS")
code = code.replace("\n_Py_bytes_lower(", "\npr_bytes_lower(")
code = code.replace("\n_Py_bytes_upper(", "\npr_bytes_upper(")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write(f"/* Generated by extract.py from {src.replace(chr(92), '/')}. */\n")
    f.write(code)
print(f"{out}: {code.count(chr(10))} lines")
