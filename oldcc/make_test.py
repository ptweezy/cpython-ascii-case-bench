"""Make a standalone test of a variant's word and block helpers: the code
from the end of _Py_bytes_istitle() up to the lower() docstring, copied
verbatim from a patched Objects/bytes_methods.c, between a small prelude
(the Python.h names it uses) and an exhaustive check against a per-byte
reference.

    python make_test.py PATCHED_BYTES_METHODS_C OUT_C
"""
import sys

PRELUDE = r"""/* Generated by oldcc/make_test.py from a patched Objects/bytes_methods.c. */
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>
#include <string.h>
typedef ptrdiff_t Py_ssize_t;
#ifdef _MSC_VER
#  ifdef _WIN64
#    define SIZEOF_SIZE_T 8
#  else
#    define SIZEOF_SIZE_T 4
#  endif
#  define Py_ALWAYS_INLINE __forceinline
#  define Py_NO_INLINE __declspec(noinline)
#else
#  define SIZEOF_SIZE_T __SIZEOF_SIZE_T__
#  define Py_ALWAYS_INLINE __attribute__((always_inline))
#  define Py_NO_INLINE __attribute__((noinline))
#endif
#define Py_ARRAY_LENGTH(a) (sizeof(a) / sizeof((a)[0]))

"""

CHECK = r"""
static int ref(int c, unsigned char first)
{
    return (c >= first && c < first + 26) ? c ^ 0x20 : c;
}

/* Every byte value at every position of every length from one word to 100
   bytes (three 32-byte blocks and an overlapping one), in both cases, at
   two source and destination offsets. */
int main(void)
{
    static char src[128], out[128];
    long bad = 0, n = 0;
    for (int off = 0; off < 2; off++) {
        int o = off ? 3 : 0;
        for (int len = SIZEOF_SIZE_T; len <= 100; len++) {
            for (int pos = 0; pos < len; pos++) {
                for (int c = 0; c < 256; c++) {
                    for (int k = 0; k < len; k++) {
                        src[o + k] = (char)("aZ@[`{\x80\xc1"[k % 8]);
                    }
                    src[o + pos] = (char)c;
                    for (int f = 0; f < 2; f++) {
                        unsigned char first = f ? 'a' : 'A';
                        ascii_case_words(out + o, src + o, len, first);
                        for (int k = 0; k < len; k++) {
                            n++;
                            if ((unsigned char)out[o + k]
                                != ref((unsigned char)src[o + k], first)) {
                                bad++;
                            }
                        }
                    }
                }
            }
        }
    }
    printf("%ld bytes checked, %ld wrong: %s\n", n, bad, bad ? "FAIL" : "ok");
    return bad != 0;
}
"""

src = open(sys.argv[1], encoding="utf-8").read()
# The helpers start after _Py_bytes_istitle(), whatever their first comment says.
start = src.index("\n}\n", src.index("\n_Py_bytes_istitle(")) + 3
end = src.index("PyDoc_STRVAR_shared(_Py_lower__doc__")
code = src[start:end]
# Only the helpers: stop before the first function that needs Python.h.
code = code[:code.index("void\n_Py_bytes_lower(")] if "void\n_Py_bytes_lower(" in code else code
open(sys.argv[2], "w", encoding="utf-8", newline="\n").write(PRELUDE + code + CHECK)
